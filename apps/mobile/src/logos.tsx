/** A provider's mark by its instance's kind, or a bot for an agent without one. */
export function ProviderLogo({ kind, size = 18, color }: { kind?: string; size?: number; color?: string }) {
  const c = useColors();
  const Mark = logos[kind ?? ""];
  const tint = color ?? c.foreground;
  return Mark ? <Mark size={size} color={tint} /> : <Bot size={size} color={tint} strokeWidth={2} />;
}
