// @ts-check
// The text `plx-connect doctor` hands the coding agent: the one-line launch prompt, the seed
// prompt around the playbook, and the context file with this computer's facts. The playbook
// itself is `doctor-playbook.md`; to change how the agent works, edit that file. Agents fetch
// the newest copy from `develop` (PLAYBOOK_URL) and follow it when it differs, so installs of an
// older plx-connect pick up playbook edits without a release.

import os from "node:os";
import path from "node:path";

/** @typedef {import("./doctor.mjs").Facts} Facts */
/** @typedef {import("./doctor.mjs").Checked} Checked */

/** Each check state's mark, as the doctor prints it. */
export const MARKS = { ok: "✓", warn: "!", fail: "✗", skip: "-" };

export const PLAYBOOK_URL = "https://raw.githubusercontent.com/ryan-stoffel/parallax/develop/packages/plx-connect/src/doctor-playbook.md";

/**
 * The one argument the agent is launched with. The instructions live in `prompt.md`: cmd.exe,
 * which runs Windows' `.cmd` shims, can't carry a multi-line argument.
 * @param {string} promptFile
 */
export const buildLaunchPrompt = (promptFile) =>
  `Read the file ${promptFile} and follow its instructions exactly: it is your Parallax doctor playbook, and it starts with asking the user what went wrong.`;

/**
 * `prompt.md`: where the context file is, then the playbook.
 * @param {string} contextFile
 * @param {string} playbook
 */
export const buildSeedPrompt = (contextFile, playbook) => `A Parallax user is having a problem \
and started this session with \`plx-connect doctor\`.

The doctor's check results and this computer's facts (versions, OS, paths, plxd's health, recent \
log errors) are in the context file:

    ${contextFile}

Follow the playbook below, starting by asking the user what went wrong.

---

${playbook}`;

/** Where `plxd service install` writes the service's file. @param {"launchd" | "systemd"} kind */
const serviceFile = (kind) =>
  kind === "launchd"
    ? path.join(os.homedir(), "Library", "LaunchAgents", "io.github.ryan-stoffel.parallax.plxd.plist")
    : path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config"), "systemd", "user", "io.github.ryan-stoffel.parallax.plxd.service");

/**
 * `context.md`: this computer's facts and the check results, pre-formatted so the playbook can
 * stay plain. It never holds a provider's env values or any key.
 * @param {{ generatedAt: string, version: string, launchedAs: string, facts: Facts, results: Checked[], sourceCache: string }} input
 */
export function buildContext({ generatedAt, version, launchedAs, facts, results, sourceCache }) {
  const { dataDir, answers } = facts;
  const data = (/** @type {string[]} */ ...parts) => path.join(dataDir, ...parts);
  const providers = answers?.providers?.providers ?? [];
  const service =
    facts.platform === "darwin"
      ? `- Login service (launchd; \`plxd service status\` reports it): ${serviceFile("launchd")}`
      : facts.platform === "linux"
        ? `- Login service (systemd user unit; \`plxd service status\`, \`journalctl --user -u io.github.ryan-stoffel.parallax.plxd\`): ${serviceFile("systemd")}`
        : "- Login service: none on Windows yet. The app starts plxd.";
  const health = answers?.health;
  return `# Parallax doctor context

Generated by \`plx-connect doctor\` at ${generatedAt}.

- Doctor version: plx-connect ${version} (the CLI that ran the checks, not Parallax's version)
- Launched as: ${launchedAs}
- OS: ${answers?.hostVersion?.os ?? process.platform} ${answers?.hostVersion?.arch ?? process.arch} (${os.release()})
- Node: ${process.version}
- Repo: https://github.com/ryan-stoffel/parallax (default branch \`develop\`)

## plxd

- Binary the doctor found: ${facts.plxd ?? "none"}${facts.plxdVersion ? ` (${facts.plxdVersion})` : ""}
- Running: ${facts.running ? `yes${facts.pid === undefined ? "" : `, pid ${facts.pid}`}` : "no"}
- Running binary: ${facts.runningExe ?? "unknown"}${facts.runningExeVersion ? ` (its version on disk now: ${facts.runningExeVersion})` : ""}
- Running version: ${answers?.initialize?.plxd ?? "unknown (plxd didn't answer)"}
- Uptime: ${health ? `${health.uptimeSeconds} s` : "unknown"}
- Project store: ${health?.store ?? "unknown"}
- Agents running a turn now: ${health?.runningAgents ?? "unknown"}
- Settings: ${answers?.settings ? Object.entries(answers.settings).map(([key, value]) => `${key} ${value}`).join(", ") : "unknown"}
- Parallax Connect: ${answers?.connect ? `Tailscale ${answers.connect.tailscale}, ${answers.connect.listening ? "listening" : "not listening"} on port ${answers.connect.port}, ${answers.connect.devices.length} other devices of this Tailscale user (${answers.connect.devices.filter((d) => d.parallax).length} on Parallax)` : "unknown"}
- Newest releases: stable ${facts.newest.stable ?? "?"}, nightly ${facts.newest.nightly ?? "?"}${facts.newest.error ? ` (couldn't check: ${facts.newest.error})` : ""}

## Agents (from plxd's \`providers/list\`)

${
  providers.length > 0
    ? providers
        .map((p) => `- ${p.instance.name} (${p.instance.kind}${p.instance.enabled === false ? ", turned off" : ""}): ${p.installed ? "installed" : "not installed"}${p.version ? ` ${p.version}` : ""}${p.signedIn === undefined ? "" : p.signedIn ? ", signed in" : ", NOT signed in"}${p.account ? ` (${p.account})` : ""}${p.note ? `. Note: ${p.note}` : ""}`)
        .join("\n")
    : `- plxd didn't answer. On PATH: ${Object.entries(facts.agentClis).map(([id, file]) => `${id} ${file ?? "missing"}`).join(", ")}`
}

## Checks

${results.map(({ name, result }) => `- ${MARKS[result.state]} ${name}: ${result.detail}`).join("\n")}

## Paths

- Data folder: ${dataDir}${facts.dataDirExists ? "" : " (doesn't exist)"}
- plxd's log: ${data("logs", "plxd.log")}
- Project store (SQLite; read only, never write): ${data("plxd.sqlite3")}
- Lock, holding the running serve's pid: ${data("plxd.lock")}
- Run worktrees: ${data("worktrees")}${facts.worktrees === undefined ? "" : ` (${facts.worktrees})`}
- Integration and coordinator worktrees: ${data("integration")}, ${data("coordinators")}
- Shared context: ${data("context")}
- Uploads: ${data("uploads")}
- plxd's own tools, such as gh: ${data("tools")}
${service}
- plxd installed by plx-connect or the app over SSH: ${path.join(os.homedir(), ".parallax-plxd")}
- Source cache (clone Parallax here): ${sourceCache}
- Secrets, NEVER read: API keys in the login Keychain (macOS) or Secret Service (Linux); ${data("providers.json")}, which can hold keys in plain text; and the agent CLIs' credential files. The playbook lists the rest.

## Recent plxd log warnings and errors (last 24 h)

${facts.log && facts.log.recent.length > 0 ? `\`\`\`\n${facts.log.recent.join("\n")}\n\`\`\`` : "None."}
`;
}
